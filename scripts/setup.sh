#!/usr/bin/env bash
# =============================================================================
# Aetheris one-command setup (Linux / macOS / WSL)
# =============================================================================
#   ./scripts/setup.sh          # create .env + MQTT password + ESPHome secrets
#   ./scripts/setup.sh --up     # ...and start the stack
#   ./scripts/setup.sh --force  # regenerate everything (overwrites secrets!)
# =============================================================================
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

FORCE=0
UP=0
for arg in "$@"; do
  case "$arg" in
    --force) FORCE=1 ;;
    --up) UP=1 ;;
    -h|--help)
      sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *) echo "Unknown argument: $arg" >&2; exit 1 ;;
  esac
done

random_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex "${1:-16}"
  else
    head -c "$(( ${1:-16} * 2 ))" /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

random_b64() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 32 | tr -d '\n'
  else
    head -c 32 /dev/urandom | base64 | tr -d '\n'
  fi
}

yaml_escape() {
  printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

echo "==> Aetheris setup"

# -----------------------------------------------------------------------------
# .env
# -----------------------------------------------------------------------------
if [ -f .env ] && [ "$FORCE" -eq 0 ]; then
  echo "    keeping existing .env"
  # shellcheck disable=SC1091
  set -a; . ./.env; set +a
else
  MQTT_PASSWORD="${MQTT_PASSWORD:-$(random_hex 12)}"
  GRAFANA_ADMIN_PASSWORD="${GRAFANA_ADMIN_PASSWORD:-$(random_hex 12)}"
  cat > .env <<EOF
# Generated by scripts/setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
TZ=${TZ:-UTC}

GRAFANA_ADMIN_USER=${GRAFANA_ADMIN_USER:-admin}
GRAFANA_ADMIN_PASSWORD=${GRAFANA_ADMIN_PASSWORD}
GRAFANA_PORT=${GRAFANA_PORT:-3000}

MQTT_USERNAME=${MQTT_USERNAME:-aetheris}
MQTT_PASSWORD=${MQTT_PASSWORD}
MQTT_PORT=${MQTT_PORT:-1883}

INFLUXDB_PORT=${INFLUXDB_PORT:-8181}
LOKI_PORT=${LOKI_PORT:-3100}
ALLOY_PORT=${ALLOY_PORT:-12345}
EXPLORER_PORT=${EXPLORER_PORT:-8888}
PORTAINER_PORT=${PORTAINER_PORT:-9000}
EOF
  chmod 600 .env
  echo "    wrote .env"
  # shellcheck disable=SC1091
  set -a; . ./.env; set +a
fi

# -----------------------------------------------------------------------------
# Mosquitto password file
# -----------------------------------------------------------------------------
if [ ! -f mosquitto/config/passwd ] || [ "$FORCE" -eq 1 ]; then
  mkdir -p mosquitto/config
  echo "    generating mosquitto/config/passwd"
  docker run --rm \
    -e MQTT_USERNAME -e MQTT_PASSWORD \
    -v "$ROOT/mosquitto/config:/mosquitto/config" \
    --entrypoint /bin/sh \
    eclipse-mosquitto:2.1.2-alpine \
    -c 'mosquitto_passwd -c -b /mosquitto/config/passwd "$MQTT_USERNAME" "$MQTT_PASSWORD" && chmod 644 /mosquitto/config/passwd'
else
  echo "    keeping existing mosquitto/config/passwd"
fi

# -----------------------------------------------------------------------------
# ESPHome secrets
# -----------------------------------------------------------------------------
SECRETS="AetherisSensorV1/secrets.yaml"
if [ ! -f "$SECRETS" ] || [ "$FORCE" -eq 1 ]; then
  WIFI_SSID="${WIFI_SSID:-}"
  WIFI_PASSWORD="${WIFI_PASSWORD:-}"
  MQTT_BROKER="${MQTT_BROKER:-}"

  if [ -t 0 ]; then
    if [ -z "$WIFI_SSID" ]; then read -r -p "    Wi-Fi SSID: " WIFI_SSID; fi
    if [ -z "$WIFI_PASSWORD" ]; then read -r -s -p "    Wi-Fi password: " WIFI_PASSWORD; echo; fi
    if [ -z "$MQTT_BROKER" ]; then
      DEFAULT_BROKER="$(hostname -I 2>/dev/null | awk '{print $1}' || true)"
      read -r -p "    MQTT broker IP [${DEFAULT_BROKER:-127.0.0.1}]: " MQTT_BROKER
      MQTT_BROKER="${MQTT_BROKER:-${DEFAULT_BROKER:-127.0.0.1}}"
    fi
  fi

  WIFI_SSID="${WIFI_SSID:-YOUR_WIFI_SSID}"
  WIFI_PASSWORD="${WIFI_PASSWORD:-YOUR_WIFI_PASSWORD}"
  MQTT_BROKER="${MQTT_BROKER:-127.0.0.1}"

  cat > "$SECRETS" <<EOF
# Generated by scripts/setup.sh
# This file is git-ignored. Keep it safe.
wifi_ssid: "$(yaml_escape "$WIFI_SSID")"
wifi_password: "$(yaml_escape "$WIFI_PASSWORD")"
wifi_ap_password: "$(random_hex 8)"

mqtt_broker: "$(yaml_escape "$MQTT_BROKER")"
mqtt_username: "$(yaml_escape "${MQTT_USERNAME:-aetheris}")"
mqtt_password: "$(yaml_escape "${MQTT_PASSWORD:-change-me}")"

api_encryption_key: "$(random_b64)"
ota_password: "$(random_hex 16)"
timezone: "${TZ:-UTC}"

# Compatibility aliases for the older single-node YAML files
ssid: "$(yaml_escape "$WIFI_SSID")"
password: "$(yaml_escape "$WIFI_PASSWORD")"
EOF
  chmod 600 "$SECRETS"
  echo "    wrote $SECRETS"
else
  echo "    keeping existing $SECRETS"
fi

# -----------------------------------------------------------------------------
# Summary
# -----------------------------------------------------------------------------
cat <<EOF

==> Setup complete

    Grafana        http://localhost:${GRAFANA_PORT:-3000}
                   user: ${GRAFANA_ADMIN_USER:-admin}
                   pass: ${GRAFANA_ADMIN_PASSWORD:-<see .env>}

    MQTT           <host-ip>:${MQTT_PORT:-1883}
                   user: ${MQTT_USERNAME:-aetheris}
                   pass: ${MQTT_PASSWORD:-<see .env>}

    Admin (local)  InfluxDB  http://127.0.0.1:${INFLUXDB_PORT:-8181}
                   Loki      http://127.0.0.1:${LOKI_PORT:-3100}

    Start          docker compose up -d
    Admin tools    docker compose --profile admin up -d

    Air nodes      see AetherisSensorV1/README.md

EOF

if [ "$UP" -eq 1 ]; then
  exec docker compose up -d
fi
