<#
.SYNOPSIS
    Aetheris one-command setup for Windows.

.EXAMPLE
    .\scripts\setup.ps1
    .\scripts\setup.ps1 -Up
    .\scripts\setup.ps1 -Force

.NOTES
    Works with Windows PowerShell 5.1 and PowerShell 7+.
    If PowerShell blocks the script, run:
        Set-ExecutionPolicy -Scope Process -ExecutionPolicy Bypass
#>
[CmdletBinding()]
param(
    [switch]$Force,
    [switch]$Up
)

$ErrorActionPreference = "Stop"

$Root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
Set-Location $Root

function Get-Setting([string]$Name, [string]$Default) {
    $value = [Environment]::GetEnvironmentVariable($Name)
    if ([string]::IsNullOrWhiteSpace($value)) { return $Default }
    return $value
}

function New-RandomHex([int]$Bytes = 16) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return (($buffer | ForEach-Object { $_.ToString("x2") }) -join "")
}

function New-RandomBase64([int]$Bytes = 32) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return [Convert]::ToBase64String($buffer)
}

function Write-TextFile([string]$Path, [string]$Content) {
    $utf8 = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Path, $Content, $utf8)
}

function ConvertTo-YamlString([string]$Value) {
    if ($null -eq $Value) { return "" }
    return $Value.Replace('\', '\\').Replace('"', '\"')
}

Write-Host "==> Aetheris setup" -ForegroundColor Cyan

# -----------------------------------------------------------------------------
# .env
# -----------------------------------------------------------------------------
$envPath = Join-Path $Root ".env"
if ((Test-Path $envPath) -and (-not $Force)) {
    Write-Host "    keeping existing .env"
}
else {
    $mqttPassword = Get-Setting "MQTT_PASSWORD" (New-RandomHex 12)
    $grafanaPassword = Get-Setting "GRAFANA_ADMIN_PASSWORD" (New-RandomHex 12)

    $envContent = @"
# Generated by scripts/setup.ps1
TZ=$(Get-Setting "TZ" "UTC")

GRAFANA_ADMIN_USER=$(Get-Setting "GRAFANA_ADMIN_USER" "admin")
GRAFANA_ADMIN_PASSWORD=$grafanaPassword
GRAFANA_PORT=$(Get-Setting "GRAFANA_PORT" "3000")

MQTT_USERNAME=$(Get-Setting "MQTT_USERNAME" "aetheris")
MQTT_PASSWORD=$mqttPassword
MQTT_PORT=$(Get-Setting "MQTT_PORT" "1883")

INFLUXDB_PORT=$(Get-Setting "INFLUXDB_PORT" "8181")
LOKI_PORT=$(Get-Setting "LOKI_PORT" "3100")
ALLOY_PORT=$(Get-Setting "ALLOY_PORT" "12345")
EXPLORER_PORT=$(Get-Setting "EXPLORER_PORT" "8888")
PORTAINER_PORT=$(Get-Setting "PORTAINER_PORT" "9000")
"@
    Write-TextFile $envPath $envContent
    Write-Host "    wrote .env"
}

# Load .env values into this session.
Get-Content $envPath | ForEach-Object {
    if ($_ -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$') {
        Set-Item -Path "env:$($matches[1])" -Value $matches[2]
    }
}

# -----------------------------------------------------------------------------
# Mosquitto password file
# -----------------------------------------------------------------------------
$passwdPath = Join-Path $Root "mosquitto\config\passwd"
if ((-not (Test-Path $passwdPath)) -or $Force) {
    New-Item -ItemType Directory -Force -Path (Split-Path $passwdPath) | Out-Null
    Write-Host "    generating mosquitto\config\passwd"
    docker run --rm `
        -e MQTT_USERNAME -e MQTT_PASSWORD `
        -v "${Root}/mosquitto/config:/mosquitto/config" `
        --entrypoint /bin/sh `
        eclipse-mosquitto:2.1.2-alpine `
        -c 'mosquitto_passwd -c -b /mosquitto/config/passwd "$MQTT_USERNAME" "$MQTT_PASSWORD" && chmod 644 /mosquitto/config/passwd'
    if ($LASTEXITCODE -ne 0) { throw "Failed to generate the Mosquitto password file." }
}
else {
    Write-Host "    keeping existing mosquitto\config\passwd"
}

# -----------------------------------------------------------------------------
# ESPHome secrets
# -----------------------------------------------------------------------------
$secretsPath = Join-Path $Root "AetherisSensorV1\secrets.yaml"
if ((-not (Test-Path $secretsPath)) -or $Force) {
    $wifiSsid = $env:WIFI_SSID
    $wifiPassword = $env:WIFI_PASSWORD
    $mqttBroker = $env:MQTT_BROKER

    if (-not $wifiSsid) { $wifiSsid = Read-Host "    Wi-Fi SSID" }
    if (-not $wifiPassword) {
        $secure = Read-Host "    Wi-Fi password" -AsSecureString
        $wifiPassword = [System.Net.NetworkCredential]::new("", $secure).Password
    }
    if (-not $mqttBroker) {
        $defaultBroker = (Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
            Where-Object { $_.IPAddress -notlike "127.*" -and $_.IPAddress -notlike "169.254.*" } |
            Select-Object -First 1 -ExpandProperty IPAddress)
        $entered = Read-Host "    MQTT broker IP [$defaultBroker]"
        $mqttBroker = if ($entered) { $entered } else { $defaultBroker }
    }

    $secretsContent = @"
# Generated by scripts/setup.ps1
# This file is git-ignored. Keep it safe.
wifi_ssid: "$(ConvertTo-YamlString $wifiSsid)"
wifi_password: "$(ConvertTo-YamlString $wifiPassword)"
wifi_ap_password: "$(New-RandomHex 8)"

mqtt_broker: "$(ConvertTo-YamlString $mqttBroker)"
mqtt_username: "$(ConvertTo-YamlString $env:MQTT_USERNAME)"
mqtt_password: "$(ConvertTo-YamlString $env:MQTT_PASSWORD)"

api_encryption_key: "$(New-RandomBase64 32)"
ota_password: "$(New-RandomHex 16)"
timezone: "$($env:TZ)"

# Compatibility aliases for the older single-node YAML files
ssid: "$(ConvertTo-YamlString $wifiSsid)"
password: "$(ConvertTo-YamlString $wifiPassword)"
"@
    Write-TextFile $secretsPath $secretsContent
    Write-Host "    wrote AetherisSensorV1\secrets.yaml"
}
else {
    Write-Host "    keeping existing AetherisSensorV1\secrets.yaml"
}

# -----------------------------------------------------------------------------
# Summary
# -----------------------------------------------------------------------------
Write-Host ""
Write-Host "==> Setup complete" -ForegroundColor Green
Write-Host ""
Write-Host "    Grafana        http://localhost:$($env:GRAFANA_PORT)"
Write-Host "                   user: $($env:GRAFANA_ADMIN_USER) / pass: $($env:GRAFANA_ADMIN_PASSWORD)"
Write-Host "    MQTT           <host-ip>:$($env:MQTT_PORT)  user: $($env:MQTT_USERNAME) / pass: $($env:MQTT_PASSWORD)"
Write-Host "    Admin (local)  InfluxDB http://127.0.0.1:$($env:INFLUXDB_PORT)   Loki http://127.0.0.1:$($env:LOKI_PORT)"
Write-Host ""
Write-Host "    Start          docker compose up -d"
Write-Host "    Admin tools    docker compose --profile admin up -d"
Write-Host "    Air nodes      see AetherisSensorV1\README.md"
Write-Host ""

if ($Up) {
    docker compose up -d
}
